"""
Experiment 1: Macro-micro decoupling case study.

This script consumes the `.npz` artifact generated by
`UncertaintyEstimatorPretrainExp.extract_residuals_on_test` and produces three
publication-ready single-panel figures:

1. Raw future trajectories.
2. Predicted macro components (`mu_hat` and `mu_hat ± sigma_hat`).
3. PDN-normalized residual futures.

Selection protocol follows the design in `docs/Analytical_experiments.md`:
  - rank windows by a deterministic drift score;
  - restrict to the high-drift subset;
  - within that subset, pick a compact group whose oracle-normalized residual
    shapes are highly correlated.
"""

